    protected function parseDepthWidthHeight(string $value, string $marketplaceId): ?array
    {
        $toInches = [
            'inches' => 1,
            'inch' => 1,
            'in' => 1,
            '"' => 1,

            'centimeters' => 0.393701,
            'centimeter' => 0.393701,
            'cm' => 0.393701,

