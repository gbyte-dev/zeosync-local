    protected function amazonCpuFamily(string $value): ?string
    {
        $value = trim($value);
        if ($value === '') {
            return null;
        }

        foreach ($this->amazonCpuFamilyValues() as $allowed) {
            if (strcasecmp($allowed, $value) === 0) {
                return $allowed;
            }
        }

        $normalized = strtolower(preg_replace('/[\s_-]+/', '_', $value));

        foreach ($this->amazonCpuFamilyValues() as $allowed) {
            if (strtolower(preg_replace('/[\s_-]+/', '_', $allowed)) === $normalized) {
                return $allowed;
            }
        }

        return null;
    }

